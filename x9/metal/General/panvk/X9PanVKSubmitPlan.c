#include "X9PanVKSubmitPlan.h"
#include "genxml/v14_pack.h"
#include <stdlib.h>
#include <string.h>
#include <errno.h>
#define MAX_JOBS 4096u
#define MAX_SYNCS 256u
struct Segment {uint64_t address;uint32_t bytes,queue;};
struct X9PanVKSubmitPlan {
 uint32_t group,segments,counts[3],wait_count,signal_count;
 struct Segment commands[MAX_JOBS];
 struct X9SyncPoint waits[MAX_SYNCS],signals[MAX_SYNCS];
};
static int error(int e){errno=e;return -1;}
static bool array_ok(struct drm_panthor_obj_array a,uint32_t size,uint32_t limit) {
 if(!a.count)return true;
 return a.count<=limit&&a.stride==size&&a.array&&!(a.array&7)&&
  a.array<=UINTPTR_MAX-(uint64_t)a.count*size;
}
static int add_point(struct X9SyncPoint *points,uint32_t *count,uint32_t handle,uint64_t value) {
 for(unsigned i=0;i<*count;i++)if(points[i].handle==handle) {
  if((points[i].point==0)!=(value==0))return error(ENOTSUP);
  if(value>points[i].point)points[i].point=value;return 0;
 }
 if(*count==MAX_SYNCS)return error(E2BIG);
 points[(*count)++]=(struct X9SyncPoint){handle,value};return 0;
}
struct X9PanVKSubmitPlan *x9_panvk_plan_create(const struct drm_panthor_group_submit *submit) {
 if(!submit||!submit->group_handle||submit->pad||
    !array_ok(submit->queue_submits,sizeof(struct drm_panthor_queue_submit),MAX_JOBS)){errno=EINVAL;return NULL;}
 struct X9PanVKSubmitPlan *p=calloc(1,sizeof(*p));if(!p)return NULL;p->group=submit->group_handle;
 bool terminal[3]={false,false,false};
 uint32_t per_wait_count[3]={0,0,0};
 struct X9SyncPoint per_waits[3][MAX_SYNCS]={0};
 const struct drm_panthor_queue_submit *jobs=(const void *)(uintptr_t)submit->queue_submits.array;
 for(unsigned i=0;i<submit->queue_submits.count;i++) {
  const struct drm_panthor_queue_submit *j=&jobs[i];
  if(j->queue_index>=3||j->pad||!array_ok(j->syncs,sizeof(struct drm_panthor_sync_op),MAX_SYNCS)||
     ((j->stream_size==0)!=(j->stream_addr==0))||(j->stream_addr&63)||(j->stream_size&7)||
     (j->stream_size&&(j->stream_addr<X9_RENDER_MIN_VA||j->stream_addr>=X9_RENDER_MAX_VA||j->stream_size>X9_RENDER_MAX_VA-j->stream_addr))) {errno=EINVAL;goto bad;}
  if(j->stream_size&&terminal[j->queue_index]){errno=ENOTSUP;goto bad;}
  const struct drm_panthor_sync_op *syncs=(const void *)(uintptr_t)j->syncs.array;
  for(unsigned k=0;k<j->syncs.count;k++) {
   const struct drm_panthor_sync_op *s=&syncs[k];uint32_t type=s->flags&DRM_PANTHOR_SYNC_OP_HANDLE_TYPE_MASK;
   if(!s->handle||(s->flags&~(0x80000000u|1u))||type>1||(!type&&s->timeline_value)){errno=EINVAL;goto bad;}
   bool signal=(s->flags&0x80000000u)!=0;
   if(type&&!s->timeline_value) {
    if(signal){errno=EINVAL;goto bad;}
    continue; /* Waiting for timeline value0 is already satisfied. */
   }
   if(!signal&&(terminal[j->queue_index]||p->counts[j->queue_index])){errno=ENOTSUP;goto bad;}
   if(signal) {
    if(add_point(p->signals,&p->signal_count,s->handle,s->timeline_value))goto bad;
   }else {
    if(add_point(p->waits,&p->wait_count,s->handle,s->timeline_value)||
       add_point(per_waits[j->queue_index],&per_wait_count[j->queue_index],s->handle,s->timeline_value))goto bad;
   }
  }
  if(j->stream_size) {
   p->commands[p->segments++]=(struct Segment){j->stream_addr,j->stream_size,j->queue_index};p->counts[j->queue_index]++;
  }
  for(unsigned k=0;k<j->syncs.count;k++)if(syncs[k].flags&0x80000000u)terminal[j->queue_index]=true;
 }
 /* Moving external waits before all streams must not hide an internal
  * dependency cycle or consume a signal generated by this batch itself. */
 for(unsigned i=0;i<p->wait_count;i++)for(unsigned j=0;j<p->signal_count;j++)
  if(p->waits[i].handle==p->signals[j].handle) {
   /* Waiting for an earlier timeline payload then publishing a later value is
    * normal. Waiting for this batch's future signal would be a cycle. Binary
    * reuse remains refused until its queue consumption is tracked. */
   if(!p->waits[i].point||!p->signals[j].point){errno=ENOTSUP;goto bad;}
   if(p->waits[i].point>=p->signals[j].point){errno=EINVAL;goto bad;}
  }
 /* A group-wide wait is equivalent only when every active queue already
  * waits on the same dependencies; otherwise another queue might be needed
  * to satisfy that dependency and the hoist could deadlock. */
 for(unsigned q=0;q<3;q++)if(p->counts[q]) {
  if(per_wait_count[q]!=p->wait_count){errno=ENOTSUP;goto bad;}
  for(unsigned i=0;i<p->wait_count;i++) {
   unsigned k=0;while(k<per_wait_count[q]&&(per_waits[q][k].handle!=p->waits[i].handle||per_waits[q][k].point!=p->waits[i].point))k++;
   if(k==per_wait_count[q]){errno=ENOTSUP;goto bad;}
  }
 }
 return p;
bad:free(p);return NULL;
}
void x9_panvk_plan_destroy(struct X9PanVKSubmitPlan *p){free(p);}
uint64_t x9_panvk_plan_stream_bytes(const struct X9PanVKSubmitPlan *p,unsigned queue) {
 return p&&queue<3?(uint64_t)p->counts[queue]*24:0;
}
int x9_panvk_plan_emit(const struct X9PanVKSubmitPlan *p,uint32_t registers,uint32_t reserved,
 const struct X9PanVKCallBuffer buffers[3],struct X9RenderStream streams[3],uint32_t *count) {
 if(!p||!buffers||!streams||!count||registers>256||registers<4||(registers&1)||reserved<4||reserved>registers)return error(EINVAL);
 /* PanVK reserves the last max(unpreserved,4) registers. Only use its final
  * four scratch registers; do not clobber persistent UMD context registers. */
 unsigned address_reg=registers-4,length_reg=registers-2;
 for(unsigned q=0;q<3;q++)if(p->counts[q]) {
  uint64_t bytes=x9_panvk_plan_stream_bytes(p,q);
  if(!buffers[q].cpu||((uintptr_t)buffers[q].cpu&7)||bytes>buffers[q].bytes||
     buffers[q].gpu<X9_RENDER_MIN_VA||(buffers[q].gpu&63)||buffers[q].gpu>=X9_RENDER_MAX_VA||
     bytes>X9_RENDER_MAX_VA-buffers[q].gpu)return error(EINVAL);
 }
 uint32_t offsets[3]={0,0,0};
 for(unsigned i=0;i<p->segments;i++) {
  const struct Segment *segment=&p->commands[i];
  uint32_t *out=(uint32_t *)((char *)buffers[segment->queue].cpu+offsets[segment->queue]);
  struct MALI_CS_MOVE48 address={MALI_CS_MOVE48_header,.destination=address_reg,.immediate=segment->address};
  struct MALI_CS_MOVE32 size={MALI_CS_MOVE32_header,.destination=length_reg,.immediate=segment->bytes};
  struct MALI_CS_CALL call={MALI_CS_CALL_header,.address=address_reg,.length=length_reg};
  MALI_CS_MOVE48_pack((struct mali_cs_move48_packed *)out,&address);
  MALI_CS_MOVE32_pack((struct mali_cs_move32_packed *)(out+2),&size);
  MALI_CS_CALL_pack((struct mali_cs_call_packed *)(out+4),&call);
  offsets[segment->queue]+=24;
 }
 *count=0;
 for(unsigned q=0;q<3;q++)if(offsets[q])streams[(*count)++]=(struct X9RenderStream){q,0,buffers[q].gpu,offsets[q]};
 return 0;
}
int x9_panvk_plan_submit(struct pan_kmod_dev *dev,const struct X9PanVKSubmitPlan *p,
 const struct X9RenderStream *streams,uint32_t count,int64_t deadline,struct X9RenderCompletion *reply) {
 if(!p||count>3||(count&&!streams))return error(EINVAL);
 if(!p->segments) {
  if(count)return error(EINVAL);
  if(reply)memset(reply,0,sizeof(*reply)); /* not a GPU completion */
  return x9_pan_kmod_sync_only(dev,p->group,p->waits,p->wait_count,p->signals,p->signal_count,deadline);
 }
 if(!count)return error(EINVAL);
 unsigned seen=0;
 for(unsigned i=0;i<count;i++) {
  unsigned q=streams[i].index;
  if(q>=3||(seen&(1u<<q))||!p->counts[q]||streams[i].bytes!=x9_panvk_plan_stream_bytes(p,q))return error(EINVAL);
  seen|=1u<<q;
 }
 for(unsigned q=0;q<3;q++)if(p->counts[q]&&!(seen&(1u<<q)))return error(EINVAL);
 /* Caller owns/mapped/cleaned CALL buffers; source streams stay pinned until
  * completion. Native engine must flush before dispatch, with no flush-ID
  * elision: original latest_flush hints are deliberately not propagated. */
 return x9_pan_kmod_submit_sync(dev,p->group,streams,count,p->waits,p->wait_count,
  p->signals,p->signal_count,deadline,reply);
}
