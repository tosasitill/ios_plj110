#!/usr/bin/env python3
"""Build/sign the small iOS torch bridge and embed it in the kernel overlay.

No device access or plugin mailbox changes. All generated bytes stay out of git.
"""
import argparse
import hashlib
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
X9 = HERE.parent


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--developer-dir', required=True, type=Path)
    ap.add_argument('--out', required=True, type=Path)
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    dev = a.developer_dir
    clang = dev / 'Toolchains/XcodeDefault.xctoolchain/usr/bin/clang'
    sdk = dev / 'Platforms/iPhoneOS.platform/Developer/SDKs/iPhoneOS.sdk'
    library = a.out / 'libx9-torch.dylib'
    cmd = [str(clang), '-target', 'arm64-apple-ios16.0', '-isysroot', str(sdk),
           '-Os', '-fobjc-arc', '-fblocks', '-Wall', '-Wextra', '-Wno-unused-parameter',
           '-dynamiclib', '-framework', 'Foundation', '-install_name', '/usr/lib/libx9-torch.dylib',
           str(HERE / 'media_bridge.m'), '-o', str(library)]
    print('building iOS 16 arm64 X9 torch bridge', flush=True)
    subprocess.run(cmd, check=True)
    subprocess.run(['/usr/bin/codesign', '--force', '--sign', '-', '--timestamp=none', str(library)], check=True)
    utility = a.out / 'torchctl'
    subprocess.run([str(clang), '-target', 'arm64-apple-ios16.0', '-isysroot', str(sdk),
                    '-Os', '-fobjc-arc', '-Wall', '-Wextra', '-framework', 'Foundation',
                    str(HERE / 'torchctl.m'), '-o', str(utility)], check=True)
    subprocess.run(['/usr/bin/codesign', '--force', '--sign', '-', '--timestamp=none', str(utility)], check=True)
    data = library.read_bytes()
    if not data or len(data) > 256 * 1024:
        raise ValueError('torch bridge outside the 256 KiB embedding budget')
    digest = hashlib.sha256(data).digest()
    path = f'/private/var/x9/torch/libx9-torch-{digest.hex()[:16]}.dylib'
    header = X9 / 'kernel/generated/x9_torch_bridge.inc'
    lines = ['/* Generated own-code bridge. Do not commit. */',
             f'#define X9_TORCH_BRIDGE_PATH "{path}"',
             'static const uint8_t x9_torch_bridge_sha[32] = {' + ','.join(f'0x{b:02x}' for b in digest) + '};',
             'static const uint8_t x9_torch_bridge_data[] = {']
    lines += [','.join(f'0x{b:02x}' for b in data[i:i+16]) + ',' for i in range(0, len(data), 16)]
    text = '\n'.join(lines) + '\n};\n'
    if not header.exists() or header.read_text() != text:
        header.parent.mkdir(parents=True, exist_ok=True)
        header.write_text(text)
    (a.out / 'torch-bridge.json').write_text(json.dumps({
        'bytes': len(data), 'sha256': digest.hex(), 'ios_path': path,
        'profile': 'iOS 16.7.16 / 20H392 / CMCapture 45d37488-2cc7-3028-8a4d-936bce7a220b',
        'hardware_tested': False}, indent=2) + '\n')
    print(f'torch bridge: {len(data)} bytes; boot-time install only with x9_torch=3', flush=True)


if __name__ == '__main__':
    main()
