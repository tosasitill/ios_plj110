#!/usr/bin/env python3
"""Embed the native-Bluetooth root payload into the kernel (x9_bt_root.inc).

The kernel's PID1 installer (x9_bluetooth_root.inc, boot-arg x9_bt_root=1)
installs exactly these files before the original launchd starts, so no
Android-side root image access is needed. --stub writes an empty header.
Generated output is gitignored; never commit it.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = ROOT / 'x9/kernel/generated/x9_bt_root.inc'
REQUIRES = (('/usr/sbin/bluetoothd', 'bluetoothd'), ('/usr/sbin/BlueTool', 'BlueTool'))
FILE_LIMIT = 4 << 20
APPLE_LIMIT = 16 << 20


def regular(base, relative, limit):
    path = (base / relative).resolve()
    if not path.is_relative_to(base.resolve()) or path.is_symlink() or not path.is_file():
        raise ValueError(f'expected regular file inside {base}: {relative}')
    data = path.read_bytes()
    if not 0 < len(data) <= limit:
        raise ValueError(f'unexpected size for {relative}: {len(data)}')
    return data


def c_string(text):
    if not text.startswith('/') or any(c in text for c in '"\\\0\n') or len(text) > 300:
        raise ValueError(f'unsupported root path: {text!r}')
    return f'"{text}"'


def c_bytes(data):
    return '{' + ','.join(f'0x{b:02x}' for b in data) + '}'


def load(payload, apple):
    meta = json.loads((payload / 'root-payload.json').read_text())
    if meta.get('kind') != 'x9-bluetooth-native-root-payload' or meta.get('ios_build') != '20H392':
        raise ValueError('not a 20H392 native Bluetooth root payload')
    originals = {item['sha256']: item for item in
                 meta['original_jobs'] + [meta['original_launchd_cache'], meta.get('original_settings')]
                 if isinstance(item, dict)}
    files = meta['files']
    if [f['path'] for f in files] != meta['install_order']:
        raise ValueError('payload file order differs from install_order')
    if files[-1]['path'] != '/System/Library/xpc/launchd.plist':
        raise ValueError('the launchd cache must be the last (commit) file')
    entries = []
    for f in files:
        data = regular(payload, f['source'], FILE_LIMIT)
        if len(data) != f['size'] or hashlib.sha256(data).hexdigest() != f['sha256']:
            raise ValueError(f'payload source does not match manifest: {f["path"]}')
        if f['uid'] != 0 or f['gid'] != 0:
            raise ValueError(f'payload owner must be 0:0: {f["path"]}')
        mode = int(f['mode'], 8)
        if mode not in (0o644, 0o755):
            raise ValueError(f'unexpected mode {f["mode"]}: {f["path"]}')
        pre = f['precondition']
        if pre == {'absent': True}:
            orig = None
        else:
            item = originals.get(pre.get('sha256'))
            if not item or item['path'] != f['path']:
                raise ValueError(f'no recorded Apple original for {f["path"]}')
            raw = regular(payload, item['source'], FILE_LIMIT)
            if len(raw) != item['size'] or hashlib.sha256(raw).hexdigest() != item['sha256']:
                raise ValueError(f'recorded Apple original differs: {f["path"]}')
            orig = (item['size'], bytes.fromhex(item['sha256']))
        entries.append((f['path'], data, mode, bytes.fromhex(f['sha256']), orig))
    requires = []
    for path, name in REQUIRES:
        data = regular(apple, name, APPLE_LIMIT)
        requires.append((path, len(data), hashlib.sha256(data).digest()))
    if requires[0][2].hex() != meta['bluetoothd_sha256']:
        raise ValueError('Apple bluetoothd original differs from the payload build identity')
    return entries, requires


def previous_versions(entries, paths):
    """Earlier payloads: {path: [(size, sha), ...]} of our own builds to upgrade."""
    known = {path: [] for path, *_ in entries}
    current = {path: sha for path, _, _, sha, _ in entries}
    for base in paths:
        meta = json.loads((base / 'root-payload.json').read_text())
        if meta.get('kind') != 'x9-bluetooth-native-root-payload' or meta.get('ios_build') != '20H392':
            raise ValueError(f'not a 20H392 native Bluetooth root payload: {base}')
        for f in meta['files']:
            sha = bytes.fromhex(f['sha256'])
            if len(sha) != 32 or f['path'] not in known or sha == current[f['path']]:
                continue
            if f['uid'] != 0 or f['gid'] != 0:
                raise ValueError(f'previous payload owner must be 0:0: {f["path"]}')
            if int(f['mode'], 8) != dict((p, m) for p, _, m, _, _ in entries)[f['path']]:
                raise ValueError(f'previous payload mode differs: {f["path"]}')
            if (f['size'], sha) not in known[f['path']]:
                known[f['path']].append((f['size'], sha))
    return known


def render(entries, requires, previous):
    lines = ['/* Native Bluetooth root payload. Generated by x9/bluetooth/root_header.py; never commit. */',
             '#define X9_BT_ROOT_PRESENT 1']
    for i, (_, data, _, _, _) in enumerate(entries):
        lines.append(f'static const uint8_t x9_btr_d{i}[{len(data)}] = {{')
        for off in range(0, len(data), 32):
            lines.append(','.join(f'0x{b:02x}' for b in data[off:off + 32]) + ',')
        lines.append('};')
    for i, (path, *_) in enumerate(entries):
        if previous[path]:
            lines.append(f'static const struct x9_btr_prev x9_btr_p{i}[] = {{')
            lines += [f' {{{size}u,{c_bytes(sha)}}},' for size, sha in previous[path]]
            lines.append('};')
    lines.append('static const struct x9_btr_file x9_btr_files[] = {')
    for i, (path, data, mode, sha, orig) in enumerate(entries):
        osize, osha = orig if orig else (0, bytes(32))
        prev = f'x9_btr_p{i},{len(previous[path])}u' if previous[path] else 'NULL,0u'
        lines.append(f' {{{c_string(path)},x9_btr_d{i},{len(data)}u,0{mode:o},{c_bytes(sha)},{osize}u,{c_bytes(osha)},{prev}}},')
    lines.append('};')
    lines.append('static const struct x9_btr_require x9_btr_requires[] = {')
    for path, size, sha in requires:
        lines.append(f' {{{c_string(path)},{size}u,{c_bytes(sha)}}},')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def write(out, text):
    out.parent.mkdir(parents=True, exist_ok=True)
    temporary = out.with_name(out.name + '.tmp')
    temporary.write_text(text)
    temporary.replace(out)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--payload', type=Path, help='candidate root-payload directory')
    ap.add_argument('--apple-originals', type=Path, help='private 20H392 bluetoothd/BlueTool originals')
    ap.add_argument('--previous-payload', type=Path, action='append', default=[],
                    help='earlier root-payload directory whose own files may be upgraded; repeatable')
    ap.add_argument('--stub', action='store_true', help='write a header that embeds nothing')
    ap.add_argument('--out', type=Path, default=DEFAULT_OUT)
    a = ap.parse_args()
    try:
        if a.stub:
            if a.payload or a.apple_originals or a.previous_payload:
                raise ValueError('--stub takes no payload')
            write(a.out, '/* No native Bluetooth root payload embedded. Generated; never commit. */\n'
                         '#define X9_BT_ROOT_PRESENT 0\n')
            print(f'stub {a.out}')
        else:
            if not a.payload or not a.apple_originals:
                raise ValueError('--payload and --apple-originals are required')
            entries, requires = load(a.payload, a.apple_originals)
            previous = previous_versions(entries, a.previous_payload)
            write(a.out, render(entries, requires, previous))
            total = sum(len(e[1]) for e in entries)
            upgrades = sum(len(v) for v in previous.values())
            print(f'embedded {len(entries)} files, {total} bytes, {upgrades} upgradable earlier versions -> {a.out}')
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as error:
        sys.exit(f'root_header failed: {error}')
