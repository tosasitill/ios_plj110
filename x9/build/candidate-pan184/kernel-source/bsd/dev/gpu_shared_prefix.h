 int32_t temper_comp_norm_gpu;
 int32_t temper_comp_high_gpu;
 int32_t temper_comp_norm_stack;
 int32_t temper_comp_high_stack;
 uint32_t cur_fgpu;
 uint32_t cur_fstack;
 uint32_t cur_out_fgpu;
 uint32_t cur_out_fstack;
 uint32_t cur_fmeter_fgpu;
 uint32_t cur_fmeter_fstack;
 uint32_t cur_vgpu;
 uint32_t cur_vstack;
