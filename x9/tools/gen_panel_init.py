#!/usr/bin/env python3
"""Generate x9/shim/panel_init_table.h from the OPPO panel dtsi.

Source of truth: panel-ac287-p-7-a0020-dsi-cmd.dtsi timing@sa_fhd_60
oplus,dsi-on-command (the sequence the kernel sends on every panel
enable, in dsi_lp_mode). Entry format is the parser's in
vendor/oplus/kernel/display_driver/oplus_drm/oplus_dsi_panel_cmd.c:

    byte0 type, byte1 cmd1, byte2 channel, byte3 flags,
    byte4 post_wait_ms, bytes5-6 count (big endian), then count bytes.

Wire type is NOT the dtsi byte0: oplus_dsi_panel_dcs_write() re-derives
it — count 1 -> DCS short write no param (0x05), count 2 -> DCS short
write one param (0x15), count > 2 -> data[0] < 0xB0 ? DCS long (0x39)
: generic long (0x29).

The generated table is consumed by display_panel_wake() in
x9/shim/display.c; do not edit the header by hand.
"""
import re
import sys

DTSI = "/tmp/oppo-modules/vendor/oplus/kernel/devicetree/oplus-display/panel-ac287-p-7-a0020-dsi-cmd.dtsi"
OUT = "x9/shim/panel_init_table.h"


def main() -> int:
    text = open(DTSI, encoding="utf-8").read()
    # timing@sa_fhd_60 is the last timing block; take the on-command
    # property that starts after its line.
    start = text.index("timing@sa_fhd_60")
    start = text.index("oplus,dsi-on-command = [", start)
    start = text.index("[", start) + 1
    end = text.index("];", start)
    body = text[start:end]
    # strip // comments, split hex bytes
    body = re.sub(r"//[^\n]*", "", body)
    b = bytes(int(x, 16) for x in body.split())

    entries = []
    i = 0
    while i < len(b):
        typ, _cmd1, _ch, flags, wait = b[i], b[i + 1], b[i + 2], b[i + 3], b[i + 4]
        count = (b[i + 5] << 8) | b[i + 6]
        data = b[i + 7 : i + 7 + count]
        if len(data) != count:
            print(f"truncated entry at byte {i}", file=sys.stderr)
            return 1
        if count == 1:
            wire = 0x05
        elif count == 2:
            wire = 0x15
        else:
            # The dtsi's own type byte (0x39) is the authority; the
            # "data[0] >= 0xB0 -> generic write" reading of
            # oplus_dsi_panel_dcs_write depends on char signedness and
            # is not reproducible - pan22 showed it does not work.
            wire = typ if typ in (0x39, 0x29) else 0x39
        entries.append((wire, wait, flags, data))
        i += 7 + count
        if i > len(b):
            break

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by x9/tools/gen_panel_init.py from\n"
                " * panel-ac287-p-7-a0020-dsi-cmd.dtsi timing@sa_fhd_60\n"
                " * oplus,dsi-on-command - do not edit by hand.\n"
                " * Flat byte pool + {type, wait_ms, flags, count, pool offset}\n"
                " * entries: the shim bans absolute relocations, so no\n"
                " * pointers are emitted - offsets index panel_init_pool[].\n"
                " */\n#ifndef PANEL_INIT_TABLE_H\n#define PANEL_INIT_TABLE_H\n\n")
        f.write("static const unsigned char panel_init_pool[] = {\n")
        for n, (wire, wait, flags, data) in enumerate(entries):
            hexarr = ", ".join(f"0x{x:02x}" for x in data)
            f.write(f"\t/* pi_{n} */ {hexarr},\n")
        f.write("};\n\n")
        f.write("static const struct panel_init_entry {\n"
                "\tunsigned char type;\n"
                "\tunsigned char wait_ms;\n"
                "\tunsigned char flags;\n"
                "\tunsigned char count;\n"
                "\tunsigned short off;\n"
                "} panel_init_table[] = {\n")
        off = 0
        for n, (wire, wait, flags, data) in enumerate(entries):
            f.write(f"\t{{{wire:#04x}, {wait:#04x}, {flags:#04x}, "
                    f"{len(data):#04x}, {off:#06x}}},\t/* pi_{n} */\n")
            off += len(data)
        f.write("};\n\n#endif /* PANEL_INIT_TABLE_H */\n")

    print(f"{len(entries)} entries, {len(b)} bytes; PPS at "
          f"{[n for n, e in enumerate(entries) if e[3][0] in (0x80, 0x81)]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
