#!/usr/bin/env python3
"""Pack the Android vendor MD OTA tree (/vendor/etc/mdota) for the X9 modem file service.

    python3 -I x9/tools/md_ota_pack.py [--src DIR] [--out FILE]

DIR is the extracted `mdota/` directory (custom/, mtk_default/, misc_data/), copied by hand into .local/x9/modem/mdota/ and
never committed. The modem's FSD serves it as drive T: (read-only). Writes <out> (default .local/x9/modem/mdota.pack) and
x9/kernel/generated/x9_mdota.inc (gitignored) which `.incbin`s the pack; without the directory it writes a stub (length 0), so
a clean checkout still builds. Pack: 'MDOT', u32 count, then count x (u16 pathlen, path, u32 size, u32 offset), then data.
"""
import argparse, hashlib, struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ap = argparse.ArgumentParser()
ap.add_argument('--src', type=Path, default=ROOT / '.local/x9/modem/mdota')
ap.add_argument('--out', type=Path, default=ROOT / '.local/x9/modem/mdota.pack')
args = ap.parse_args()
inc = ROOT / 'x9/kernel/generated/x9_mdota.inc'

files = []
if args.src.is_dir():
    for p in sorted(args.src.rglob('*')):
        if p.is_file() and not p.is_symlink():
            files.append((p.relative_to(args.src).as_posix(), p.read_bytes()))
if files:
    table = b''.join(struct.pack('<H', len(n)) + n.encode() + b'\0\0\0\0\0\0\0\0' for n, _ in files)
    base = 8 + len(table)
    out = bytearray(b'MDOT' + struct.pack('<I', len(files)))
    off = base
    for n, d in files:
        out += struct.pack('<H', len(n)) + n.encode() + struct.pack('<II', len(d), off)
        off += (len(d) + 15) & ~15
    assert len(out) == base
    for n, d in files:
        out += d + b'\0' * (((len(d) + 15) & ~15) - len(d))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.exists() or args.out.read_bytes() != bytes(out):
        args.out.write_bytes(bytes(out))
    digest = hashlib.sha256(out).hexdigest()
    text = ('/* Generated by x9/tools/md_ota_pack.py; vendor data, keep out of git. */\n'
            f'/* sha256 {digest} (changes this file so ccache cannot reuse an object built with an older pack) */\n'
            '#define X9_MDOTA_PRESENT 1\n'
            f'#define X9_MDOTA_FILES {len(files)}\n'
            '__asm__(".section __TEXT,__const\\n.p2align 4\\n.globl _x9_mdota_pack\\n_x9_mdota_pack:\\n'
            f'.incbin \\"{args.out}\\"\\n.globl _x9_mdota_pack_end\\n_x9_mdota_pack_end:\\n.text\\n");\n'
            'extern const unsigned char x9_mdota_pack[], x9_mdota_pack_end[];\n')
    print(f'mdota: {len(files)} files, {len(out)} bytes, sha256 {digest[:16]}')
else:
    text = ('/* Generated by x9/tools/md_ota_pack.py: no .local/x9/modem/mdota, stub. */\n'
            '#define X9_MDOTA_PRESENT 0\n#define X9_MDOTA_FILES 0\n'
            'static const unsigned char x9_mdota_pack[8]={0};\n#define x9_mdota_pack_end (x9_mdota_pack+8)\n')
    print('mdota: no source directory, stub')
if not inc.exists() or inc.read_text() != text:
    inc.write_text(text)
