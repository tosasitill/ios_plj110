#!/usr/bin/env python3
"""Embed the MT6653 Wi-Fi firmware into the X9 kernel.

    python3 -I x9/tools/wifi_firmware.py [--src DIR] [--out FILE]

Reads the vendor firmware the device's Android image ships (copied by hand to
.local/x9/wifi-fw/, never committed) and writes x9/kernel/generated/
x9_wifi_firmware.inc (gitignored) with the ROM patch, the WM RAM code and the
PHY RAM code as byte arrays plus their SHA-256. Without the directory it
writes a stub (X9_WIFI_FW_PRESENT 0), so a clean checkout still builds and
the kernel simply skips the firmware stages. The output is rewritten only
when its content changes, so incremental kernel builds stay incremental.

The ROM patch is checked against the gen4m PATCH_FORMAT_V2 layout
(chips/common/fw_dl.c wlanGetPatchInfoAndDownloadV2): 32-byte header with
u4PatchVersion 0xffffffff, 64-byte big-endian global descriptor, then one
64-byte section map per section.
"""
import argparse
import hashlib
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VARIANT = 'dx5_2g2a_1'
FILES = (
    ('patch', f'WIFI_MT6653_PATCH_MCU_{VARIANT}_hdr.bin'),
    ('ram', f'WIFI_RAM_CODE_MT6653_{VARIANT}.bin'),
    ('phy', f'WIFI_MT6653_PHY_RAM_CODE_{VARIANT}.bin'),
)


def check_patch(blob):
    if len(blob) < 96 or struct.unpack_from('<I', blob, 24)[0] != 0xffffffff:
        raise ValueError('ROM patch is not PATCH_FORMAT_V2 (u4PatchVersion != 0xffffffff)')
    nsec = struct.unpack_from('>I', blob, 32 + 12)[0]
    if not 1 <= nsec <= 8 or 96 + 64 * nsec > len(blob):
        raise ValueError(f'ROM patch section count {nsec} out of range')
    rows = []
    for i in range(nsec):
        typ, off, size, addr, dl_size, sec_info = struct.unpack_from('>6I', blob, 96 + 64 * i)
        if (typ & 0xffff) == 2 and (off + dl_size > len(blob) or dl_size > size):
            raise ValueError(f'ROM patch section {i} outside the file')
        rows.append(f'sec{i} type={typ:08x} off={off:#x} size={dl_size:#x} addr={addr:#010x} info={sec_info:08x}')
    return rows


def render(src):
    out = ['/* Generated by x9/tools/wifi_firmware.py; vendor firmware, keep out of git. */']
    present = all((src / name).is_file() for _, name in FILES)
    out.append(f'#define X9_WIFI_FW_PRESENT {1 if present else 0}')
    notes = []
    for key, name in FILES:
        blob = (src / name).read_bytes() if present else b''
        if key == 'patch' and blob:
            notes = check_patch(blob)
        digest = hashlib.sha256(blob).hexdigest() if blob else ''
        out.append(f'static const char x9_wifi_{key}_name[] = "{name if blob else ""}";')
        out.append(f'static const char x9_wifi_{key}_sha256[] = "{digest}";')
        out.append(f'static const unsigned int x9_wifi_{key}_len = {len(blob)}u;')
        out.append(f'static const unsigned char x9_wifi_{key}[] __attribute__((aligned(16))) = {{')
        data = blob or b'\0'
        for at in range(0, len(data), 32):
            out.append(','.join(str(v) for v in data[at:at + 32]) + ',')
        out.append('};')
    return '\n'.join(out) + '\n', present, notes


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--src', type=Path, default=ROOT / '.local/x9/wifi-fw')
    ap.add_argument('--out', type=Path, default=ROOT / 'x9/kernel/generated/x9_wifi_firmware.inc')
    a = ap.parse_args()
    try:
        text, present, notes = render(a.src)
    except (OSError, ValueError) as e:
        sys.exit(f'wifi_firmware: {e}')
    old = a.out.read_text() if a.out.is_file() else None
    if old != text:
        a.out.write_text(text)
    state = 'unchanged' if old == text else 'written'
    print(f'wifi firmware: {"embedded from " + str(a.src) if present else "absent (stub)"}; {a.out.name} {state}')
    for line in notes:
        print(f'wifi firmware: patch {line}')


if __name__ == '__main__':
    main()
