#!/usr/bin/env python3
"""Embed the device's MT6653 Wi-Fi NVRAM (calibration / TX power) into the X9 kernel.

    python3 -I x9/tools/wifi_nvram.py [--src FILE] [--out FILE]

Reads the NVRAM record Android keeps in nvdata (APCFG/APRDEB/WIFI, 11266 B on
this device; copied by hand to .local/x9/wifi-nvram/WIFI, never committed: it
holds the device MAC and its calibration) and writes x9/kernel/generated/
x9_wifi_nvram.inc (gitignored) with the 37 fragments gen4m sends
(common/wlan_lib.c wlanLoadManufactureData, is_support_nvram_fragment): the
first runs from offset 0 through the first TLV (ucTypeID0 at 256), each next one
is one TLV {u8 id, u16 le length, data}, until an all-zero tag. Without the file
it writes a stub (X9_WIFI_NVRAM_PRESENT 0). Rewritten only when content changes.

Also (rev252ca) the pre-RAM PHY_ACTION payloads (gen4m chips/common/pre_cal.c): the ePA/eLNA tag data
wlanGetEpaElnaFromNvram picks from the NVRAM (tags 7, 8, 9, 21 and any id with bit 7, inside the NVRAM's
own total size; 632 B here, giving Android's CAL LEN 880), and, when .local/x9/wifi-nvram/connfem.dts
exists, the connfem SKU tag (x9/tools/wifi_connfem.py, 606 B here, Android's COM_FEM LEN 682).
"""
import argparse
import hashlib
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from wifi_connfem import sku_tag  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
FIRST_TAG = 256          # OFFSET_OF(struct WIFI_CFG_PARAM_STRUCT, ucTypeID0)
FRAGMENT_MAX = 1500      # sizeof(struct CMD_NVRAM_FRAGMENT)


def fragments(blob):
    out, start, off = [], 0, FIRST_TAG
    if len(blob) < FIRST_TAG + 3:
        raise ValueError('NVRAM shorter than its fixed header')
    while True:
        tid, lsb, msb = blob[off], blob[off + 1], blob[off + 2]
        off += 3 + (msb << 8 | lsb)
        if off > len(blob):
            raise ValueError(f'TLV id {tid} runs past the end ({off} > {len(blob)})')
        if off - start > FRAGMENT_MAX:
            raise ValueError(f'TLV id {tid} fragment {off - start} B > {FRAGMENT_MAX}')
        out.append((start, off - start, tid))
        start = off
        if off + 3 > len(blob) or blob[off:off + 3] == b'\0\0\0':
            return out


def epaelna(blob):
    off = FIRST_TAG
    if blob[off] != 0:
        return b''
    total = (blob[off + 5] << 8 | blob[off + 4]) + 256
    out = bytearray()
    while off < total and off + 3 <= len(blob):
        tid, n = blob[off], blob[off + 1] | blob[off + 2] << 8
        if tid == 0 and n == 0:
            break
        if tid in (7, 8, 9, 21) or tid & 0x80:
            out += blob[off:off + 3 + n]
        off += 3 + n
    return bytes(out)


def carray(name, data):
    lines = [f'static const uint8_t {name}[{max(len(data), 1)}] = {{']
    for i in range(0, len(data), 24):
        lines.append(' ' + ','.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',')
    if not data:
        lines.append(' 0')
    lines.append('};')
    return lines


def render(blob, frags):
    lines = ['/* generated by x9/tools/wifi_nvram.py - device data, never commit */',
             '#define X9_WIFI_NVRAM_PRESENT 1',
             f'#define X9_WIFI_NVRAM_SHA256 "{hashlib.sha256(blob).hexdigest()}"',
             f'static const uint8_t x9_wifi_nvram[{len(blob)}] = {{']
    for i in range(0, len(blob), 24):
        lines.append(' ' + ','.join(f'0x{b:02x}' for b in blob[i:i + 24]) + ',')
    lines.append('};')
    lines.append('/* {offset, length, first TLV id} per fragment, in send order */')
    lines.append(f'static const uint16_t x9_wifi_nvram_frag[{len(frags)}][3] = {{')
    lines += [f' {{{s},{n},{t}}},' for s, n, t in frags]
    lines.append('};')
    ep = epaelna(blob)
    lines.append(f'#define X9_WIFI_EPAELNA_LEN {len(ep)}')
    lines += carray('x9_wifi_epaelna', ep)
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', type=Path, default=ROOT / '.local/x9/wifi-nvram/WIFI')
    ap.add_argument('--out', type=Path, default=ROOT / 'x9/kernel/generated/x9_wifi_nvram.inc')
    ap.add_argument('--connfem', type=Path, default=None)
    ap.add_argument('--required', action='store_true', help='reject absent calibration/connfem instead of generating stubs')
    a = ap.parse_args()
    cf = a.connfem or a.src.with_name('connfem.dts')
    if a.required and (not a.src.is_file() or not cf.is_file()):
        sys.exit(f'wifi_nvram: required WIFI/connfem input absent at {a.src.parent}; no stub written')
    if a.src.is_file():
        blob = a.src.read_bytes()
        frags = fragments(blob)
        text = render(blob, frags)
        note = f'{len(blob)} B, {len(frags)} fragments, sha256 {hashlib.sha256(blob).hexdigest()[:16]}, ' \
            f'epaelna {len(epaelna(blob))} B'
    else:
        text = '/* generated by x9/tools/wifi_nvram.py: no NVRAM file */\n#define X9_WIFI_NVRAM_PRESENT 0\n'
        note = f'stub ({a.src} absent)'
    if cf.is_file():
        tag = sku_tag(cf.read_text())
        text += '\n'.join(['#define X9_WIFI_CONNFEM_PRESENT 1', f'#define X9_WIFI_CONNFEM_LEN {len(tag)}']
                          + carray('x9_wifi_connfem_sku', tag)) + '\n'
        note += f', connfem SKU tag {len(tag)} B'
    else:
        text += '#define X9_WIFI_CONNFEM_PRESENT 0\n'
        note += ', no connfem'
    if not a.out.is_file() or a.out.read_text() != text:
        a.out.write_text(text)
    print(f'wifi_nvram: {note}')


if __name__ == '__main__':
    sys.exit(main())
