#!/usr/bin/env python3
"""Package original D22AP/20H392 Mav17 firmware for the boot-time ABM view.

Inputs and generated files stay outside git. This never contacts a device,
patches Apple code, personalizes firmware, or supplies firmware to the MTK MD.
With no input, emit an explicit empty build stub rather than retaining old data.
"""
import argparse
import hashlib
import io
import json
import plistlib
import re
import struct
import zipfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCAL = ROOT / '.local/x9/baseband'
GENERATED = ROOT / 'x9/kernel/generated/x9_baseband_firmware.inc'
MAX_FILE = 64 * 1024 * 1024
MAX_TOTAL = 96 * 1024 * 1024


def changed(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_bytes() != data:
        temporary = path.with_suffix(path.suffix + '.tmp')
        temporary.write_bytes(data)
        temporary.replace(path)


def c_digest(data):
    return '{' + ','.join(f'0x{x:02x}' for x in hashlib.sha256(data).digest()) + '}'


def load_bbfw(args):
    if args.ipsw:
        with zipfile.ZipFile(args.ipsw) as ipsw:
            manifest = plistlib.loads(ipsw.read('BuildManifest.plist'))
            if manifest.get('ProductBuildVersion') != '20H392' or 'iPhone10,3' not in manifest.get('SupportedProductTypes', []):
                raise ValueError('requires the original iPhone10,3 20H392 IPSW')
            paths = {b['Manifest']['BasebandFirmware']['Info']['Path'] for b in manifest['BuildIdentities']
                     if b['Info'].get('DeviceClass') == 'd22ap' and 'BasebandFirmware' in b['Manifest']}
            if len(paths) != 1:
                raise ValueError('D22AP manifest must select exactly one baseband firmware')
            name = paths.pop()
            if name != 'Firmware/Mav17-9.00.02.Release.bbfw':
                raise ValueError(f'unexpected D22AP firmware selection: {name}')
            entry = ipsw.getinfo(name)
            if entry.file_size > MAX_TOTAL:
                raise ValueError('oversized bbfw')
            raw = ipsw.read(entry)
            changed(LOCAL / 'Mav17-9.00.02.Release.bbfw', raw)
            changed(LOCAL / 'BuildManifest.plist', ipsw.read('BuildManifest.plist'))
            return raw, str(args.ipsw.resolve()) + ':' + name
    if not args.src.exists():
        if args.src != LOCAL / 'Mav17-9.00.02.Release.bbfw':
            raise FileNotFoundError(args.src)
        return None, None
    if args.src.stat().st_size > MAX_TOTAL:
        raise ValueError('oversized bbfw')
    return args.src.read_bytes(), str(args.src.resolve())


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--ipsw', type=Path, help='extract the manifest-selected D22AP firmware from a local original IPSW')
    ap.add_argument('--src', type=Path, default=LOCAL / 'Mav17-9.00.02.Release.bbfw')
    ap.add_argument('--out', type=Path, default=LOCAL / 'Mav17.pack')
    ap.add_argument('--header', type=Path, default=GENERATED)
    ap.add_argument('--metadata', type=Path, default=LOCAL / 'Mav17-source.json')
    ap.add_argument('--storage', choices=['embedded', 'external'], default='embedded',
                    help='external emits only the built-in file/hash manifest; pack stays out of boot.img')
    ap.add_argument('--none', action='store_true', help='emit the empty stub even if the default input exists')
    ap.add_argument('--exclude', default='', help='diagnostic-only incomplete subset; cannot satisfy BBUpdater boot validation')
    ap.add_argument('--allow-incomplete', action='store_true', help='explicitly allow diagnostic --exclude (never for external delivery)')
    args = ap.parse_args()
    raw, source = (None, None) if args.none else load_bbfw(args)
    header = '/* Generated by x9/tools/baseband_firmware.py; original Apple firmware, never commit. */\n'
    if raw is None:
        changed(args.header, (header + '#define X9_BBFW_PRESENT 0\n').encode())
        changed(args.metadata, b'{"storage": "absent", "complete": false}\n')
        print('baseband firmware: absent; explicit empty stub (no ABM firmware view)')
        return
    files, names, total = [], set(), 0
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        entries = archive.infolist()
        if not 1 <= len(entries) <= 256:
            raise ValueError('invalid firmware file count')
        for item in sorted(entries, key=lambda i: i.filename):
            name = item.filename
            # Flat, non-executable Mav17 assets only; no compat/CommCenter input.
            mode = (item.external_attr >> 16) & 0o170000
            if not re.fullmatch(r'[A-Za-z0-9_-]+\.(mbn|plist)', name) or mode not in (0, 0o100000):
                raise ValueError(f'unsupported firmware member: {name}')
            if name.casefold() in names or item.flag_bits & 1 or item.file_size > MAX_FILE:
                raise ValueError(f'invalid firmware member: {name}')
            names.add(name.casefold())
            total += item.file_size
            if total > MAX_TOTAL:
                raise ValueError('oversized unpacked firmware')
            data = archive.read(item)  # ZIP CRC verified here, inside normal packaging.
            files.append((name, data))
    excluded = {x for x in args.exclude.split(',') if x}
    if excluded - {n for n, _ in files}:
        raise ValueError('unknown excluded firmware member')
    if excluded and (not args.allow_incomplete or args.storage == 'external'):
        raise ValueError('--exclude requires --allow-incomplete; external delivery must be complete')
    required = {'Info.plist', 'Options.plist', 'sbl1.mbn', 'restoresbl1.mbn', 'mba.mbn',
                'qdsp6sw.mbn', 'apps.mbn', 'rpm.mbn', 'tz.mbn', 'acdb.mbn', 'bbcfg.mbn'}
    if not required.issubset({n for n, _ in files}):
        raise ValueError('incomplete original Mav17 firmware')
    info = plistlib.loads(dict(files)['Info.plist'])
    files = [(n, d) for n, d in files if n not in excluded]
    if not files:
        raise ValueError('empty diagnostic firmware subset')
    if info.get('com.apple.EmbeddedSoftwareRestore.Baseband.Version') != '9.00.02' or info.get('com.apple.EmbeddedSoftwareRestore.Baseband.ChipId') != '0x0003B0E1':
        raise ValueError('firmware Info.plist does not match D22AP Mav17')
    pack = bytearray(b'X9BBF001' + struct.pack('<II', len(files), 0))
    records, table = [], []
    for name, data in files:
        compressed = zlib.compress(data, 9)
        offset = len(pack)
        pack += compressed
        table.append(f'  {{"{name}",{offset}u,{len(compressed)}u,{len(data)}u,{c_digest(data)}}},')
        records.append({'name': name, 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest(),
                        'offset': offset, 'packed_bytes': len(compressed)})
    if args.storage == 'embedded' and len(pack) > 4 * 1024 * 1024:
        raise ValueError('firmware pack exceeds 4 MiB embedded budget; use --storage external, not a large boot.img')
    absolute = str(args.out.resolve())
    if any(c in absolute for c in ('"', '\\', '\n', '\r')):
        raise ValueError('unsupported .incbin path')
    text = (header + f'/* archive SHA256 {hashlib.sha256(pack).hexdigest()} */\n'
            '#define X9_BBFW_PRESENT 1\n'
            f'#define X9_BBFW_EXTERNAL {int(args.storage == "external")}\n'
            f'#define X9_BBFW_COMPLETE {int(not excluded)}\n'
            f'#define X9_BBFW_PACK_BYTES {len(pack)}u\n'
            f'static const uint8_t x9_bbfw_pack_sha256[32]={c_digest(pack)};\n'
            'struct x9_bbfw_file { const char *name; uint32_t offset, packed, bytes; uint8_t sha256[32]; };\n'
            'static const struct x9_bbfw_file x9_bbfw_files[]={\n' + '\n'.join(table) + '\n};\n')
    if args.storage == 'embedded':
        text += ('__asm__(".section __TEXT,__const\\n.p2align 4\\n.globl _x9_bbfw_pack\\n_x9_bbfw_pack:\\n'
            f'.incbin \\"{absolute}\\"\\n.globl _x9_bbfw_pack_end\\n_x9_bbfw_pack_end:\\n.text\\n");\n'
            'extern const uint8_t x9_bbfw_pack[],x9_bbfw_pack_end[];\n')
    changed(args.out, bytes(pack))
    changed(args.header, text.encode())
    changed(args.metadata, (json.dumps({'build': '20H392', 'device_class': 'd22ap',
            'storage': args.storage, 'complete': not excluded, 'excluded': sorted(excluded),
            'pack_bytes': len(pack), 'allocation_bytes': ((len(pack) + (2 << 20) - 1) // (2 << 20)) * (2 << 20),
            'source': source, 'bbfw_sha256': hashlib.sha256(raw).hexdigest(),
            'pack_sha256': hashlib.sha256(pack).hexdigest(), 'files': records}, indent=2) + '\n').encode())
    print(f'baseband firmware: {args.storage}, complete={not excluded}, original 20H392 Mav17, '
          f'{len(files)} files, {sum(len(d) for _, d in files)} selected/{total} original bytes, {len(pack)} packed bytes')
    if excluded:
        print('WARNING: diagnostic subset only; qdsp6sw.mbn is REQUIRED by validateBootupItems, not optional for boot')


if __name__ == '__main__':
    main()
