/* x9-rootexec: the controlled root execution helper for the storm prefix.
 *
 * Installed setuid root (mode 4755) under /var/storm/usr/bin. A request is
 *   x9-rootexec <verb> [args...]     verb in {dpkg, apt-get, uicache}
 * Authorization, in order (any failure exits nonzero, nothing executes):
 *   1. effective uid is 0 (the setuid bit actually took effect);
 *   2. the parent process is a pinned caller (path + SHA256, see
 *      caller_check.h) -- the Sileo app binary; giveMeRoot execs this
 *      helper, so the parent is Sileo itself;
 *   3. (verb, args) passes rootexec_policy.h.
 * The target binary is a fixed absolute path, execve'd directly with a
 * scrubbed environment. No shell is involved at any point.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <errno.h>
#include "rootexec_policy.h"
#include "caller_check.h"
#include "rootexec_callers.h" /* generated by build.py */

extern char **environ;

static void audit(const char *caller, const char *verb, const char *what) {
    fprintf(stderr, "x9-rootexec: %s caller=%s verb=%s\n", what,
            caller ? caller : "?", verb ? verb : "?");
    FILE *log = fopen("/private/var/mobile/Library/X9Storm/rootexec.log", "a");
    if (log) {
        fprintf(log, "%s caller=%s verb=%s\n", what, caller ? caller : "?",
                verb ? verb : "?");
        fclose(log);
    }
}

int main(int argc, char **argv) {
    if (geteuid() != 0) {
        fprintf(stderr, "x9-rootexec: not privileged (setuid ineffective?)\n");
        return 3;
    }
    char caller[PROC_PIDPATHINFO_MAXSIZE] = "";
    if (!x9_caller_authorized(X9_ROOTEXEC_CALLERS,
                              sizeof(X9_ROOTEXEC_CALLERS) / sizeof(X9_ROOTEXEC_CALLERS[0]),
                              caller, sizeof caller)) {
        audit(caller, argc > 1 ? argv[1] : NULL, "deny-caller");
        return 4;
    }
    if (argc < 2) {
        fprintf(stderr, "usage: x9-rootexec <dpkg|apt-get|uicache> [args...]\n");
        return 2;
    }
    const x9_verb_rule *rule = NULL;
    x9_decision d = x9_validate(argv[1], argc - 2, argv + 2, &rule);
    if (d != X9_ALLOW) {
        audit(caller, argv[1], "deny-policy");
        return 5;
    }
    char *args[20];
    args[0] = (char *)rule->binary;
    int n = argc - 2;
    for (int i = 0; i < n; i++) args[i + 1] = argv[i + 2];
    args[n + 1] = NULL;
    char *env[] = {
        "PATH=/var/storm/usr/bin:/var/storm/usr/sbin",
        "HOME=/private/var/mobile",
        "LANG=C",
        "DEBIAN_FRONTEND=noninteractive",
        NULL
    };
    audit(caller, argv[1], "exec");
    execve(rule->binary, args, env);
    fprintf(stderr, "x9-rootexec: execve %s: %s\n", rule->binary, strerror(errno));
    return 6;
}
